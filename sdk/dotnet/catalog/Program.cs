// determinismo-catalog: writes a .NET project's assertion catalog, DeterminismoCatalog.g.cs, whose
// module initializer declares every call to the SDK's assertions whose message is a literal, so
// that an assertion no timeline reaches is judged too (Antithesis's catalog; Antithesis's .NET SDK
// generates the same with a source generator). Run it before building:
//
//   dotnet run --project sdk/dotnet/catalog -- <project directory>...
//
// Every .cs file under each directory is read (bin/ and obj/ left out).

using System.Text;

var assertions = new Dictionary<string, (string Kind, int Position)>
{
    ["Always"] = ("always", 1), ["AlwaysOrUnreachable"] = ("always_or_unreachable", 1),
    ["Sometimes"] = ("sometimes", 1), ["Reachable"] = ("reachable", 0), ["Unreachable"] = ("unreachable", 0),
    ["AlwaysSome"] = ("always", 1), ["SometimesAll"] = ("sometimes", 1),
};
foreach (var relation in new[] { "GreaterThan", "GreaterThanOrEqualTo", "LessThan", "LessThanOrEqualTo" })
{
    assertions["Always" + relation] = ("always", 2);
    assertions["Sometimes" + relation] = ("sometimes", 2);
}

var directories = args.Length > 0 ? args : new[] { "." };
foreach (var directory in directories)
{
    var found = new SortedSet<(string Kind, string Message)>();
    foreach (var file in Directory.EnumerateFiles(directory, "*.cs", SearchOption.AllDirectories))
    {
        var parts = file.Split(Path.DirectorySeparatorChar);
        if (parts.Contains("bin") || parts.Contains("obj") || file.EndsWith("DeterminismoCatalog.g.cs")) continue;
        Scan(File.ReadAllText(file), assertions, found);
    }
    var output = new StringBuilder();
    output.AppendLine("// Generated by determinismo-catalog (sdk/dotnet/catalog): do not edit.");
    output.AppendLine("namespace Determinismo.Generated;");
    output.AppendLine();
    output.AppendLine("internal static class DeterminismoCatalog");
    output.AppendLine("{");
    output.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
    output.AppendLine("    internal static void Declare()");
    output.AppendLine("    {");
    foreach (var (kind, message) in found)
        output.AppendLine($"        global::Determinismo.Catalog.Declare(\"{kind}\", {Literal(message)});");
    output.AppendLine("    }");
    output.AppendLine("}");
    File.WriteAllText(Path.Combine(directory, "DeterminismoCatalog.g.cs"), output.ToString());
    Console.Error.WriteLine($"determinismo-catalog: {found.Count} assertions in {directory}");
}

// Calls `Assert.<Name>(` (or `Determinismo.Assert.<Name>(`) whose argument at the assertion's
// position is a plain string literal.
static void Scan(string source, Dictionary<string, (string Kind, int Position)> assertions,
    SortedSet<(string, string)> found)
{
    const string prefix = "Assert.";
    for (var at = source.IndexOf(prefix, StringComparison.Ordinal); at >= 0;
         at = source.IndexOf(prefix, at + prefix.Length, StringComparison.Ordinal))
    {
        if (at > 0 && (char.IsLetterOrDigit(source[at - 1]) || source[at - 1] == '_')) continue;
        var nameStart = at + prefix.Length;
        var nameEnd = nameStart;
        while (nameEnd < source.Length && (char.IsLetterOrDigit(source[nameEnd]) || source[nameEnd] == '_')) nameEnd++;
        var name = source[nameStart..nameEnd];
        if (!assertions.TryGetValue(name, out var assertion)) continue;
        var open = nameEnd;
        while (open < source.Length && char.IsWhiteSpace(source[open])) open++;
        if (open >= source.Length || source[open] != '(') continue;
        var arguments = Arguments(source, open + 1);
        if (assertion.Position >= arguments.Count) continue;
        var message = StringLiteral(arguments[assertion.Position].Trim());
        if (message != null) found.Add((assertion.Kind, message));
    }
}

// The call's arguments as text, split at its top-level commas.
static List<string> Arguments(string source, int start)
{
    var arguments = new List<string>();
    var depth = 0;
    var current = new StringBuilder();
    for (var at = start; at < source.Length; at++)
    {
        var c = source[at];
        if (c == '"' || c == '\'')
        {
            var verbatim = c == '"' && at > 0 && source[at - 1] == '@';
            var end = SkipQuoted(source, at, verbatim);
            current.Append(source, at, end - at);
            at = end - 1;
            continue;
        }
        if (c == '<' && at > 0 && (char.IsLetterOrDigit(source[at - 1]) || source[at - 1] == '_'))
        {
            var end = GenericEnd(source, at);
            if (end > at)
            {
                current.Append(source, at, end - at);
                at = end - 1;
                continue;
            }
        }
        if (c is '(' or '[' or '{') depth++;
        if (c is ')' or ']' or '}')
        {
            if (depth == 0)
            {
                arguments.Add(current.ToString());
                return arguments;
            }
            depth--;
        }
        if (c == ',' && depth == 0)
        {
            arguments.Add(current.ToString());
            current.Clear();
            continue;
        }
        current.Append(c);
    }
    return arguments;
}

// Past a generic type list starting at `at` (`<string, bool>`, nested ones too), or `at` when it
// is not one (a comparison: other characters before its `>`).
static int GenericEnd(string source, int at)
{
    var depth = 0;
    for (var index = at; index < source.Length; index++)
    {
        var c = source[index];
        if (c == '<') depth++;
        else if (c == '>')
        {
            depth--;
            if (depth == 0) return index + 1;
        }
        else if (!(char.IsLetterOrDigit(c) || char.IsWhiteSpace(c) || c is '_' or ',' or '.' or '?' or '[' or ']')) return at;
    }
    return at;
}

// Past a quoted literal starting at `at` (escapes, or a verbatim string's doubled quotes).
static int SkipQuoted(string source, int at, bool verbatim)
{
    var quote = source[at];
    for (var index = at + 1; index < source.Length; index++)
    {
        if (verbatim)
        {
            if (source[index] == '"')
            {
                if (index + 1 < source.Length && source[index + 1] == '"') { index++; continue; }
                return index + 1;
            }
            continue;
        }
        if (source[index] == '\\') { index++; continue; }
        if (source[index] == quote) return index + 1;
    }
    return source.Length;
}

// A plain "..." literal's value (escapes \\ \" \n \t), else null (interpolated, computed).
static string? StringLiteral(string text)
{
    if (text.Length < 2 || text[0] != '"' || text[^1] != '"') return null;
    var value = new StringBuilder();
    for (var index = 1; index < text.Length - 1; index++)
    {
        var c = text[index];
        if (c == '"') return null; // Two literals joined: computed.
        if (c != '\\') { value.Append(c); continue; }
        index++;
        if (index >= text.Length - 1) return null;
        value.Append(text[index] switch { 'n' => '\n', 't' => '\t', 'r' => '\r', '0' => '\0', var other => other });
    }
    return value.ToString();
}

static string Literal(string value)
{
    var output = new StringBuilder("\"");
    foreach (var c in value)
    {
        output.Append(c switch
        {
            '"' => "\\\"", '\\' => "\\\\", '\n' => "\\n", '\r' => "\\r", '\t' => "\\t",
            _ when c < ' ' => $"\\u{(int)c:x4}",
            _ => c.ToString(),
        });
    }
    return output.Append('"').ToString();
}
